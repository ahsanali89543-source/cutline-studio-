export function matchesTag(look: CaptionLook, tag: string): boolean {
  if (tag === "All") return true;
  if (tag === "PRO") return Boolean(look.pro);
  if (tag === "Business") return look.tag === "Business" || look.tag === "Finance" || look.tag === "Tech" || look.tag === "Luxury";
  return look.tag === tag;
}

export function sampleWords(sample: string | undefined, fallback = "yeh scene dekho"): Word[] {
  const parts = (sample || fallback).split(/\s+/).filter(Boolean).slice(0, 6);
  return parts.map((text, index) => ({
    id: `s${index}-${text}`,
    text,
    start: index * 0.42,
    end: index * 0.42 + 0.4,
    emphasis: false,
  }));
}

